// The "What's new" page shows the repo's CHANGELOG.md; this turns the file into a list of its lines in the app.
val generateChangelog = tasks.register("generateChangelog") {
    val changelog = rootProject.layout.projectDirectory.file("CHANGELOG.md")
    val output = layout.buildDirectory.dir("generated/changelog/kotlin")
    inputs.file(changelog)
    outputs.dir(output)
    doLast {
        val lines = changelog.asFile.readLines().joinToString(",\n") { line ->
            "    \"" + line.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        }
        val file = output.get().file("io/github/agopalareddy/umm/settings/ChangelogLines.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package io.github.agopalareddy.umm.settings\n\n" +
                "/** CHANGELOG.md, line by line. Generated by :ui:generateChangelog; edit CHANGELOG.md instead. */\n" +
                "internal val changelogLines: List<String> = listOf(\n$lines,\n)\n",
        )
    }
}

